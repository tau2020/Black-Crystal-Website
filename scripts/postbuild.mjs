// Writes host configuration next to the static output (dist/client):
//   _redirects  — Netlify / Cloudflare Pages (301s for legacy WordPress URLs)
//   _headers    — Netlify / Cloudflare Pages (security + cache headers)
//   .htaccess   — Apache (current blackcrystal.co.zw host): HTTPS + canonical host, 301s, headers, caching
import { writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { legacyRedirects } from '../src/data/redirects.mjs';
import { cacheRules, securityHeaders } from './security-headers.mjs';

const out = path.resolve('dist/client');
await access(out);

const canonicalHost = new URL(process.env.SITE_URL ?? 'https://blackcrystal.co.zw').host;
const strip = (p) => p.replace(/\/$/, '');

// ── _redirects ──────────────────────────────────────────────────────────────
const redirectLines = legacyRedirects.flatMap(({ from, to }) => {
  const base = strip(from);
  return [`${base} ${to} 301`, `${base}/ ${to} 301`];
});
await writeFile(
  path.join(out, '_redirects'),
  `# Generated by scripts/postbuild.mjs — legacy WordPress URLs\n${redirectLines.join('\n')}\n`,
);

// ── _headers ────────────────────────────────────────────────────────────────
const headerBlock = (pattern, headers) =>
  [pattern, ...Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`)].join('\n');
const headersFile = [
  headerBlock('/*', securityHeaders),
  ...cacheRules.map((r) => headerBlock(`${r.prefix}*`, { 'Cache-Control': r.value })),
].join('\n\n');
await writeFile(path.join(out, '_headers'), `# Generated by scripts/postbuild.mjs\n${headersFile}\n`);

// ── .htaccess ───────────────────────────────────────────────────────────────
const escapeRegex = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const rewriteRules = legacyRedirects.map(({ from, to, hostOnly }) => {
  const source = strip(from).replace(/^\//, '');
  // WordPress emitted some slugs with a trailing zero-width space (%E2%80%8B); match with or without it.
  const pattern = hostOnly
    ? `^${escapeRegex(source.replace(/%E2%80%8B$/i, ''))}[^/]*/?$`
    : `^${escapeRegex(source)}/?$`;
  return `RewriteRule ${pattern} ${to} [R=301,L,NE]`;
});
const htaccess = `# Generated by scripts/postbuild.mjs — Apache configuration for the static site.
# The contact form needs the Node server (dist/server) or an equivalent endpoint; see ARCHITECTURE.md.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On
# HTTPS and canonical host (${canonicalHost})
RewriteCond %{HTTPS} !=on [OR]
RewriteCond %{HTTP_HOST} !^${escapeRegex(canonicalHost)}$ [NC]
RewriteRule ^ https://${canonicalHost}%{REQUEST_URI} [R=301,L,NE]

# Legacy WordPress URLs
${rewriteRules.join('\n')}
</IfModule>

<IfModule mod_headers.c>
${Object.entries(securityHeaders)
  .map(([k, v]) => `Header always set ${k} "${v}"`)
  .join('\n')}
<FilesMatch "\\.(js|css|woff2|avif|webp|png|jpg|svg)$">
  Header set Cache-Control "public, max-age=604800"
</FilesMatch>
</IfModule>

<IfModule mod_expires.c>
ExpiresActive On
ExpiresByType video/mp4 "access plus 30 days"
</IfModule>

AddType video/mp4 .mp4
AddType image/avif .avif
AddType image/webp .webp
AddType font/woff2 .woff2
AddType application/manifest+json .webmanifest
`;
await writeFile(path.join(out, '.htaccess'), htaccess);
console.log(
  `postbuild: wrote _redirects (${redirectLines.length} rules), _headers, .htaccess (${rewriteRules.length} rewrites)`,
);
